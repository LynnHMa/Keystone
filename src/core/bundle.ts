import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { KeystoneEngine } from "./engine.js";
import type { MemoryDocument } from "./types.js";

export interface BundleResult {
  outDir: string;
  files: Array<{ name: string; path: string; bytes: number; docsIncluded: number }>;
}

function isIdentityDoc(doc: MemoryDocument): boolean {
  const hay = `${doc.id} ${doc.title} ${doc.tags.join(" ")}`.toLowerCase();
  return (
    doc.kind === "correction" ||
    hay.includes("identity") ||
    hay.includes("persona") ||
    hay.includes("principle") ||
    hay.includes("protocol") ||
    hay.includes("profile") ||
    hay.includes("contract")
  );
}

/**
 * Compiles the Git-backed memory repository into 3 compact, high-signal Markdown
 * bundles suitable for web AI platforms (Gemini Gems + Google Drive, AI Studio,
 * Claude Projects, NotebookLM).
 */
export function buildMemoryBundle(
  engine: KeystoneEngine,
  opts: { bankId?: string; outDir?: string; maxEpisodes?: number } = {}
): BundleResult {
  const bankId = opts.bankId || engine.config.globalBankId;
  const outDir = opts.outDir || join(engine.config.repoDir, ".cache", "bundle");
  const maxEpisodes = opts.maxEpisodes ?? 30;
  mkdirSync(outDir, { recursive: true });

  const allFiles = engine.store.listAllMemoryFiles();
  const docs: MemoryDocument[] = [];
  for (const rel of allFiles) {
    for (const d of engine.store.parseFile(rel)) {
      if (d.bankId === bankId || d.bankId === engine.config.globalBankId) {
        docs.push(d);
      }
    }
  }

  // Compute superseded IDs so stale facts are excluded from the bundle
  const superseded = new Set<string>();
  for (const d of docs) {
    for (const oldId of d.supersedes) superseded.add(oldId);
  }
  const active = docs.filter((d) => !superseded.has(d.id));

  const identityAndCorrections = active
    .filter((d) => d.kind === "correction" || (d.kind === "page" && isIdentityDoc(d)))
    .sort((a, b) => {
      if (a.kind === "correction" && b.kind !== "correction") return -1;
      if (b.kind === "correction" && a.kind !== "correction") return 1;
      return b.updatedAt.localeCompare(a.updatedAt);
    });

  const identityIds = new Set(identityAndCorrections.map((d) => d.id));
  const knowledgePages = active
    .filter((d) => (d.kind === "page" || d.kind === "initiative") && !identityIds.has(d.id))
    .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));

  const recentTimeline = active
    .filter((d) => d.kind === "observation" || d.kind === "world" || d.kind === "experience")
    .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))
    .slice(0, maxEpisodes);

  const now = new Date().toISOString();
  const renderSection = (header: string, list: MemoryDocument[], maxPerDocChars: number) => {
    const chunks = [`# ${header}\n`, `> Generated by Keystone at ${now} (${list.length} memories)\n`];
    for (const d of list) {
      const body =
        d.content.length > maxPerDocChars
          ? d.content.slice(0, maxPerDocChars).trimEnd() + "\n\n*(truncated)*"
          : d.content;
      chunks.push(
        `\n---\n\n## [${d.kind.toUpperCase()}] ${d.title}\n` +
          `- ID: \`${d.id}\` | Bank: \`${d.bankId}\` | Harness: \`${d.harness}\` | Updated: ${d.updatedAt}\n\n` +
          body +
          "\n"
      );
    }
    return chunks.join("");
  };

  const specs: Array<{ name: string; content: string; count: number }> = [
    {
      name: "01_Identity_And_Corrections.md",
      content: renderSection("Keystone Core Identity, Laws & Verified Corrections", identityAndCorrections, 5000),
      count: identityAndCorrections.length
    },
    {
      name: "02_Knowledge_Pages.md",
      content: renderSection("Keystone Mental Model Pages & Active Initiatives", knowledgePages, 4500),
      count: knowledgePages.length
    },
    {
      name: "03_Recent_Timeline.md",
      content: renderSection("Keystone Recent Observations & Episodes", recentTimeline, 1800),
      count: recentTimeline.length
    }
  ];

  const outFiles: BundleResult["files"] = [];
  for (const s of specs) {
    const abs = join(outDir, s.name);
    writeFileSync(abs, s.content, "utf8");
    outFiles.push({
      name: s.name,
      path: abs,
      bytes: Buffer.byteLength(s.content, "utf8"),
      docsIncluded: s.count
    });
  }

  return { outDir, files: outFiles };
}
